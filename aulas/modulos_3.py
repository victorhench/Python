import emoji

print(emoji.emojize("Olá, mundo :earth_americas:", language="alias"))

# emoji é uma biblioteca externa que permite trabalhar com emojis no Python
# emojize transforma o código do emoji em um emoji de verdade
# :earth_americas: representa o emoji do planeta Terra
# language="alias" permite usar os nomes alternativos dos emojis
# bibliotecas externas podem ser instaladas usando o comando pip install no terminal